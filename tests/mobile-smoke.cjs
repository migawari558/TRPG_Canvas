const {app,BrowserWindow}=require('electron');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs/promises');
const output=path.resolve('.test-output/mobile');
app.setPath('userData',path.join(output,`profile-${Date.now()}`));
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
app.whenReady().then(async()=>{try{
 await fs.mkdir(output,{recursive:true});
 const win=new BrowserWindow({width:412,height:820,show:false,webPreferences:{sandbox:true,contextIsolation:true}});
 const errors=[];win.webContents.on('console-message',event=>{if(event.level==='error')errors.push(event.message);});
 const js=async code=>{const value=await win.webContents.executeJavaScript(code,true);await delay(120);return value;};
 const label=text=>js(`document.querySelector('[aria-label=${JSON.stringify(text)}]').click()`);
 await win.loadFile(path.resolve('.test-output/mobile-dist/index.html'));await delay(700);win.show();win.focus();
 await js(`Array.from(document.querySelectorAll('button')).find(button=>button.textContent.includes('新しいシナリオ')).click()`);await delay(300);
 assert.ok(await js(`!!document.querySelector('[aria-label="シナリオ本文"]')`));
 await label('目次を開く');assert.equal(await js(`document.querySelector('.mobile-drawer').classList.contains('outline')`),true);
 await js(`document.querySelector('.mobile-heading').click()`);assert.equal(await js(`!!document.querySelector('.mobile-drawer')`),false);
 await label('執筆メモを開く');assert.equal(await js(`document.querySelector('.mobile-drawer').classList.contains('notes')`),true);
 await label('パネルを閉じる');
 await js(`Array.from(document.querySelectorAll('.mobile-switchbar nav button')).find(button=>button.textContent==='フロー').click()`);
 assert.equal(await js(`document.querySelectorAll('.node-edit,.flow-actions').length`),0);
 await js(`Array.from(document.querySelectorAll('.mobile-switchbar nav button')).find(button=>button.textContent==='本文').click()`);
 await js(`(()=>{const input=document.querySelector('.mobile-title');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'スマホ下書き');input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
 await js(`(()=>{const node=document.querySelector('[aria-label="シナリオ本文"] p'),range=document.createRange();range.selectNodeContents(node);getSelection().removeAllRanges();getSelection().addRange(range);node.closest('.tiptap').focus();})()`);
 await label('太字（Ctrl+B）');assert.ok(await js(`!!document.querySelector('[aria-label="シナリオ本文"] strong')`));
 await delay(900);
 win.setSize(412,520);await delay(200);
 assert.ok(await js(`(()=>{const bar=document.querySelector('.editor-toolbar').getBoundingClientRect(),view=document.querySelector('.mobile-app').getBoundingClientRect();return bar.bottom<=view.bottom+1&&bar.bottom>=view.bottom-2;})()`),'修飾バーが表示領域の下端にありません');
 await fs.writeFile(path.join(output,'keyboard-height.png'),(await win.webContents.capturePage()).toPNG());
 await label('シナリオ一覧へ戻る');await delay(200);
 assert.ok(await js(`Array.from(document.querySelectorAll('.mobile-document')).some(button=>button.textContent.includes('スマホ下書き'))`));
 win.webContents.reload();await delay(900);
 await js(`document.querySelector('.mobile-document').click()`);await delay(200);
 assert.equal(await js(`document.querySelector('.mobile-title').value`),'スマホ下書き');
 assert.ok(await js(`!!document.querySelector('[aria-label="シナリオ本文"] strong')`));
 assert.deepEqual(errors,[]);console.log('PASS: mobile drawers, view-only flow, formatting above keyboard viewport, draft persistence');app.exit(0);
}catch(error){console.error(error);app.exit(1);}});
