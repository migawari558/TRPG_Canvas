const {app,BrowserWindow}=require('electron');
const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict');
const output=path.resolve('.test-output/mobile-design');
app.setPath('userData',path.join(output,`profile-${Date.now()}`));
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
app.whenReady().then(async()=>{try{
 await fs.mkdir(output,{recursive:true});
 const {sampleDocument}=await import('../src/model.mjs');
 const win=new BrowserWindow({width:430,height:900,show:false,webPreferences:{sandbox:true,contextIsolation:true}});
 win.setContentSize(412,820);
 win.webContents.on('console-message',event=>{if(event.level==='error')console.error('RENDERER:',event.message)});
 const js=async code=>{const result=await win.webContents.executeJavaScript(code,true);await delay(100);return result;};
 const label=text=>js(`document.querySelector('[aria-label=${JSON.stringify(text)}]').click()`);
 const capture=async name=>fs.writeFile(path.join(output,name),(await win.webContents.capturePage()).toPNG());
 await win.loadFile(path.resolve('.test-output/mobile-dist/index.html'));await delay(600);win.showInactive();
 const doc=sampleDocument();
 await js(`new Promise((resolve,reject)=>{const r=indexedDB.open('trpg-canvas-mobile',1);r.onsuccess=()=>{const db=r.result,tx=db.transaction('drafts','readwrite');tx.objectStore('drafts').put({key:'design-sample',doc:${JSON.stringify(doc)}});tx.oncomplete=()=>{db.close();resolve()};tx.onerror=()=>reject(tx.error)}})`);
 win.webContents.reload();await delay(700);
 await capture('home.png');
 assert.notEqual(await js(`getComputedStyle(document.querySelector('.mobile-swipe-draft')).backgroundColor`),'rgb(172, 68, 61)','Resting home row must not expose a red deletion background');
 assert.ok(await js(`document.documentElement.scrollWidth<=innerWidth`));
 await js(`(()=>{const i=document.querySelector('[aria-label="下書きを検索"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(i,'一致しない検索語');i.dispatchEvent(new Event('input',{bubbles:true}));})()`);
 assert.equal(await js(`document.querySelectorAll('.mobile-document').length`),0);
 await label('下書き検索をクリア');
 assert.equal(await js(`document.querySelectorAll('.mobile-document').length`),1);
 await label(`${doc.title}の下書きを削除`);
 assert.ok(await js(`document.querySelector('.mobile-delete-dialog').textContent.includes('元ファイルは削除しません')`));
 await capture('delete-confirmation.png');
 await js(`Array.from(document.querySelectorAll('.mobile-delete-dialog button')).find(b=>b.textContent==='キャンセル').click()`);
 await js(`(()=>{const row=document.querySelector('.mobile-swipe-draft');row.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:1,pointerType:'touch',clientX:290,clientY:280}));row.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,pointerId:1,pointerType:'touch',clientX:190,clientY:281}));})()`);
 await capture('swipe.png');
 assert.ok(await js(`document.querySelector('.mobile-swipe-delete').getBoundingClientRect().width>70`));
 await js(`document.querySelector('.mobile-swipe-draft').dispatchEvent(new PointerEvent('pointercancel',{bubbles:true,pointerId:1,pointerType:'touch'}))`);
 assert.equal(await js(`document.querySelector('.mobile-swipe-delete').hidden`),true);
 await js(`document.querySelector('.mobile-document').click()`);
 const statusTouch=await js(`(()=>{const b=document.querySelector('.mobile-save-state > button');return{height:b.getBoundingClientRect().height,minHeight:getComputedStyle(b).minHeight}})()`);
 assert.ok(statusTouch.height>=47.9,JSON.stringify(statusTouch));
 await label('目次を開く');
 assert.ok(await js(`(()=>{const r=document.querySelector('.mobile-drawer-close').getBoundingClientRect();return r.width>=47.9&&r.height>=47.9})()`));
 await capture('outline.png');
 const search='目次を検索';
 await js(`(()=>{const input=document.querySelector('[aria-label="${search}"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'喫茶店');input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
 assert.equal(await js(`document.querySelectorAll('.mobile-outline-row').length`),2);
 await capture('outline-search.png');
 await label('パネルを閉じる');
 await capture('editor.png');
 for(const width of [360,412,768]){win.setContentSize(width,820);await delay(150);assert.ok(await js(`document.documentElement.scrollWidth<=innerWidth`));}
 win.setContentSize(412,820);
 await js(`document.querySelectorAll('.mobile-switchbar nav button')[1].click()`);
 assert.equal(await js(`document.querySelectorAll('.mobile-flow-scene').length`),doc.flow.nodes.filter(node=>node.type!=='sceneGroup').length);
 await capture('flow.png');
 await label('シナリオ一覧へ戻る');
 await label('スマホの設定');
 await js(`(()=>{const s=document.querySelector('[aria-label="スマホ配色テーマ"]');s.value='midnight';s.dispatchEvent(new Event('change',{bubbles:true}));})()`);
 await label('設定を閉じる');
 await capture('home-dark.png');
 console.log('PASS: no red overflow at rest, explicit deletion confirmation/cancel, swipe reveal/reset, outline search with ancestry, mobile widths and dark theme');
 app.exit(0);
}catch(error){console.error(error);app.exit(1)}});
